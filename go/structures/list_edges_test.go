package structures

import (
	"github.com/stretchr/testify/require"
	"lab3sem3/internal/testutil"
	"testing"
)

func TestListInvalidPositions(t *testing.T) {
	testutil.Capture(t, func() {
		l := NewFList()
		l.FDeleteFirst()
		l.FDeleteEnd()
		l.FDeleteValue("x")
		l.FDeleteIndex(-1)
		l.FAddAfter(nil, "x")
		l.FAddBefore(nil, "x")
		l.FAddIndex("x", 9)
		l.FDeleteBefore(nil)
		l.FDeleteAfter(nil)
		l.FAddIndex("a", 0)
		l.FAddEnd("b")
		l.FAddEnd("c")
		foreign := &ListNode{Chislo: "outside"}
		l.FAddBefore(foreign, "x")
		l.FDeleteBefore(foreign)
		l.FDeleteBefore(l.head)
		l.FDeleteAfter(l.head.Next.Next)
		l.FAddIndex("x", -1)
		l.FDeleteIndex(20)
		require.Equal(t, []string{"a", "b", "c"}, fValues(l))
		l.FDeleteBefore(l.head.Next)
		l.FDeleteEnd()
		l.FDeleteIndex(0)
		require.Empty(t, fValues(l))
		l.FAddEnd("x")
		l.FDeleteEnd()
		require.Nil(t, l.head)
		d := NewLList()
		d.LDeleteFirst()
		d.LDeleteEnd()
		d.LDeleteNode(nil)
		d.LDeleteAfter(nil)
		d.LDeleteBefore(nil)
		d.LAddAfter(nil, "x")
		d.LAddBefore(nil, "x")
		d.LAddIndex("x", -1)
		d.LAddIndex("x", 9)
		d.LDeleteIndex(-1)
		d.LDeleteIndex(8)
		d.LDeleteValue("x")
		d.LAddIndex("a", 0)
		d.LAddEnd("b")
		d.LDeleteBefore(d.head)
		d.LDeleteAfter(d.tail)
		d.LDeleteAfter(d.head)
		require.Equal(t, []string{"a"}, lValues(t, d))
		d.LAddAfter(d.head, "b")
		d.LAddAfter(d.head, "middle")
		d.LDeleteBefore(d.head.Next)
		d.LDeleteNode(d.head)
		d.LDeleteEnd()
		require.Empty(t, lValues(t, d))
		d.LAddFirst("z")
		d.LDeleteFirst()
		require.Nil(t, d.tail)
	})
}
